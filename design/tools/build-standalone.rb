# Builds design/components-standalone.html: components.html with tokens.css, components.css and the
# Geist fonts inlined (fonts as base64 data URLs), so the sheet opens on its own after downloading.
# Run from the repo root:   ruby design/tools/build-standalone.rb
# Review tooling only: the app itself still has no build step.
require 'base64'

dir = File.expand_path('..', __dir__)
html = File.read(File.join(dir, 'components.html'), encoding: 'utf-8')
tokens = File.read(File.join(dir, 'tokens.css'), encoding: 'utf-8')
comps = File.read(File.join(dir, 'components.css'), encoding: 'utf-8')

comps = comps.gsub(%r{url\(fonts/([A-Za-z-]+\.woff2)\)}) do
  data = File.binread(File.join(dir, 'fonts', Regexp.last_match(1)))
  "url(data:font/woff2;base64,#{Base64.strict_encode64(data)})"
end

[['<link rel="stylesheet" href="tokens.css">', tokens], ['<link rel="stylesheet" href="components.css">', comps]].each do |tag, css|
  html.include?(tag) or abort "components.html: missing #{tag}"
  html = html.sub(tag) { "<style>\n#{css}</style>" }
end
html = html.sub('<title>Ride Together design system: components</title>',
                "<title>Ride Together design system: components (standalone)</title>\n<!-- Generated by design/tools/build-standalone.rb from components.html, tokens.css and components.css. Edit those, then rebuild. Fonts: Geist and Geist Mono, SIL OFL 1.1 (design/fonts/OFL.txt). -->")
File.write(File.join(dir, 'components-standalone.html'), html)
puts "Wrote design/components-standalone.html (#{(html.bytesize / 1024.0).round} KB)"
